/**
 * t(key) — returns translated string for the current UI language.
 * Falls back to English if key missing in current lang.
 * Usage in popup.js: window._t('generating')
 */
window._t = function(key) {
  const lang = window._uiLang || 'en';
  const dict = window.I18N[lang] || window.I18N.en;
  return dict[key] ?? window.I18N.en[key] ?? key;
};
